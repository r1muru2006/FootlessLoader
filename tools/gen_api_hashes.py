#!/usr/bin/env python3
"""Generate compile-time API hash constants for the loader.

The loader must not embed the plaintext names of the APIs it resolves.
This script hashes the fixed API list for every resolver variant and emits
src/api_hashes.h.  The build seed is fixed per binary; see build.sh.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

MASK32 = 0xFFFFFFFF
DEFAULT_SEED = 0x13579BDF

MODULES = ("ntdll.dll", "kernel32.dll")

# (module index, export name) in the exact order used by footless_init_api_table.
APIS = (
    (0, "RtlGetVersion"),
    (0, "NtClose"),
    (0, "NtOpenProcess"),
    (0, "NtAllocateVirtualMemory"),
    (0, "NtWriteVirtualMemory"),
    (0, "NtReadVirtualMemory"),
    (0, "NtProtectVirtualMemory"),
    (0, "NtFreeVirtualMemory"),
    (0, "NtCreateThreadEx"),
    (0, "NtOpenThread"),
    (0, "NtQueueApcThread"),
    (0, "NtQuerySystemInformation"),
    (0, "NtCreateSection"),
    (0, "NtMapViewOfSection"),
    (0, "NtUnmapViewOfSection"),
    (0, "NtWaitForSingleObject"),
    (0, "NtQueryInformationProcess"),
    (1, "LoadLibraryW"),
    (1, "CreateRemoteThread"),
    (1, "QueryFullProcessImageNameW"),
    (1, "IsWow64Process"),
    (1, "GetExitCodeThread"),
    (1, "CloseHandle"),
    (1, "WaitForSingleObject"),
    (1, "FlushInstructionCache"),
    (1, "Sleep"),
    (1, "GetThreadId"),
)


def rol32(value: int, count: int) -> int:
    count &= 31
    if count == 0:
        return value & MASK32
    return ((value << count) | (value >> (32 - count))) & MASK32


def feed(state: int, byte: int) -> int:
    state = rol32(state, 5)
    state ^= byte
    return (state + 0x9E3779B9) & MASK32


def hash_baseline(text: str, seed: int) -> int:
    state = (0x811C9DC5 ^ seed) & MASK32
    for byte in text.encode("ascii"):
        state ^= byte
        state = (state * 0x01000193) & MASK32
    return state


def hash_seeded(text: str, seed: int) -> int:
    state = (0xA5A5A5A5 ^ seed) & MASK32
    for byte in text.encode("ascii"):
        state = feed(state, byte)
    return state


def hash_module_api(module: str, api: str, seed: int) -> int:
    state = (0xA5A5A5A5 ^ seed) & MASK32
    for byte in module.encode("ascii"):
        state = feed(state, byte)
    state = feed(state, ord(":"))
    for byte in api.encode("ascii"):
        state = feed(state, byte)
    return state


def build(seed: int) -> str:
    module_hashes = [hash_baseline(name, seed) for name in MODULES]
    rows = []
    for index, (module_index, api) in enumerate(APIS):
        module = MODULES[module_index]
        rows.append(
            (
                index,
                module_index,
                api,
                (
                    hash_baseline(api, seed),
                    hash_seeded(api, seed),
                    hash_module_api(module, api, seed),
                ),
            )
        )
    lines = [
        "/* Generated by tools/gen_api_hashes.py - do not edit by hand. */",
        "#ifndef FOOTLESS_API_HASHES_H",
        "#define FOOTLESS_API_HASHES_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define FOOTLESS_GENERATED_SEED UINT32_C(0x{seed:08x})",
        f"#define FOOTLESS_GENERATED_API_COUNT {len(APIS)}",
        "",
        "static const uint32_t footless_generated_module_hash["
        f"{len(MODULES)}] = {{",
        "    " + ", ".join(f"UINT32_C(0x{v:08x})" for v in module_hashes),
        "};",
        "",
        "static const uint8_t footless_generated_module_index["
        f"{len(APIS)}] = {{",
    ]
    for start in range(0, len(APIS), 12):
        chunk = rows[start : start + 12]
        lines.append("    " + ", ".join(str(r[1]) for r in chunk) + ("," if start + 12 < len(APIS) else ""))
    lines += [
        "};",
        "",
        "static const uint32_t footless_generated_api_hash["
        f"{len(APIS)}][3] = {{",
    ]
    for row in rows:
        values = ", ".join(f"UINT32_C(0x{v:08x})" for v in row[3])
        lines.append(f"    {{{values}}}, /* {row[2]} */")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", type=lambda value: int(value, 0), default=DEFAULT_SEED)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "src" / "api_hashes.h",
    )
    args = parser.parse_args()
    args.out.write_text(build(args.seed), encoding="utf-8")
    print(f"wrote {args.out} ({len(APIS)} APIs, seed 0x{args.seed:08x})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
